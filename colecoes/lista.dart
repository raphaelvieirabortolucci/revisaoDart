void main() {
  List<String> names = ["John", "Jane", "Bob"];
  List<String> fruits = ["Apple", "Banana", "Orange"];
  for (var fruit in fruits) {
    print(fruit);
  }
  print(names);

}

//tipos
// list.add -> adiciona um elemento no final da lista
// list.remove -> remove um elemento da lista
// list.length -> retorna o tamanho da lista
// list.contains -> verifica se um elemento está na lista
// list.indexOf -> retorna o índice de um elemento na lista
// list.sort -> ordena a lista
// list.clear -> remove todos os elementos da lista
// list.isEmpty -> verifica se a lista está vazia
// list.isNotEmpty -> verifica se a lista não está vazia
// list.reversed -> retorna a lista invertida
// list.join -> retorna uma string com os elementos da lista separados por um separador
// list.sublist -> retorna uma sublista a partir de um índice
// list.map -> aplica uma função a cada elemento da lista e retorna uma nova lista
// list.where -> retorna uma nova lista com os elementos que satisfazem uma condição
// list.forEach -> aplica uma função a cada elemento da lista
// list.reduce -> reduz a lista a um único valor aplicando uma função
// list.fold -> reduz a lista a um único valor aplicando uma função e um valor inicial
// list.any -> verifica se algum elemento da lista satisfaz uma condição
